/**
 * The "anchoring" side of the character fixed-appearance library.
 *
 * Before tags are generated, the library text (all entries) goes into the request: the AI must see each character's current field values
 * to judge whether they need changing; in image tags it copies the library field values verbatim, without placeholders.
 *
 * Why no @name placeholders (withdrawn since v0.1.2): the original design had the AI write only @小雪 and the plugin replace it with
 * the full field string, to stop paraphrase drift. In practice it had three structural problems:
 * - when one character was referenced several times, each reference expanded, so one image got three full appearances + three 1boy,
 *   and the model drew several overlapping torsos (positive weight tripled; negative tags couldn't hold it).
 * - the spec's "40 tags or fewer" budget became unenforceable: the AI counts @小雪 as 1, but it expands to 6.
 * - dirty library data was amplified unconditionally: an action/scene word that slipped into the outfit field came along on every expansion.
 * The library text is already in the same context with the field values plainly listed, and copying visible text is more reliable than
 * reciting from memory; the original design overestimated the drift risk. So it reverted to "library is reference only; the AI writes it out in full".
 *
 * The applyCharRefs family is kept: if the model occasionally writes @name, it still gets replaced, so the literal never
 * reaches image generation. In other words, demoted from the main path to a fallback.
 *
 * Profile creation is done by the main request in the same output (changes with field="new"): BaiBai Book's Chinese appearance text already
 * goes to the main request with the character reference block, and the main request also has the lorebook, character card and target text as evidence,
 * so it judges better than a separate conversion request. Creating and using a profile happen in one inference, so later tags can be built around the appearance just established.
 *
 * Main flow order: apply changes first (changes on this floor take effect on this floor) → then replace any leftover @placeholders as a fallback.
 */

/** Renders a library entry as one line for the AI (field-style details + placeholder hint); locked entries carry a [locked] marker. */
export function formatEntryForPrompt(entry: CharTagEntry, locked = false): string {
  const parts: string[] = [];
  for (const f of CHAR_TAG_FIELDS) {
    const v = entry.fields[f]?.trim();
    if (v) parts.push(`${CHAR_TAG_FIELD_LABELS[f]}=${v}`);
  }
  if (!parts.length && entry.raw.trim()) parts.push(`tag=${entry.raw.trim()}`);
  if (entry.nl.trim()) parts.push(`nl=${entry.nl.trim()}`);
  return `- ${entry.name}${locked ? ' [locked]' : ''}: ${parts.join(', ') || '(field not recorded)'}`;
}

/**
 * Library text: the character library part sent to the AI. The AI decides changes from it and copies the matching fields into tag/nl;
 * both the list and the field values are generated by the plugin; the AI only reads them. Locked names (global library) carry a [locked] marker, and the header declares them immutable.
 */
export function buildLibraryText(entries: CharTagEntry[], lockedNames?: ReadonlySet<string>): string {
  if (!entries.length) return '';
  const lines = entries.map(entry => formatEntryForPrompt(entry, lockedNames?.has(entry.name) ?? false));
  const lockedNote = lockedNames?.size
    ? '; entries marked [locked] are global and immutable: never report changes for them, always copy their fields as-is'
    : '';
  return `【 character fixed appearance library 】[system-maintained; copy fields verbatim into character prompts${lockedNote}]\n${lines.join('\n')}`;
}

/** Legacy interface compatibility: callers outside the runner still depend on the anchor-text shape. */
export function buildAnchorText(entries: CharTagEntry[], lockedNames?: ReadonlySet<string>): string {
  return buildLibraryText(entries, lockedNames);
}

/* ============ Batch conversion of CJK appearance text → structured fields ============ */

const CONVERT_SPEC = `You are looking for tag converter. Split the given Chinese appearance description of the character into fixed fields danbooru short tag: English lowercase, comma separated, multiple words connected with spaces (do not use underscores).

Fields and examples:
- sex (gender): 1girl / 1boy / androgynous etc.
- hair (hair): long black hair / short silver hair etc.
- eyes (eyes): red eyes / blue eyes etc.
- skin (skin color): tan / dark skin, etc. (leave blank if not mentioned; fair is the default skin color and does not need to be recorded)
- body (body type): petite / tall / slim / small breasts, etc.
- extra (logo characteristics): heterochromia / scar on cheek / pointy ears, etc. (leave blank if not mentioned)

Rules:
1. Only fixed basic features are extracted; clothing, accessories, status, expressions, actions, and scenes are not included.
2. hair and eyes are two-dimensional character identity anchors: as long as hair color, hairstyle/length or eye color clues appear in the description, they must be written in the corresponding fields and must not be left out or stuffed into extra; hair should try to retain both color and length/hairstyle, and eyes should retain the color.
3. Don’t make up for the details not mentioned in the description, and leave empty strings in the corresponding fields.
4. Only one JSON is returned Object: {"Character name":{"sex":"...","hair":"...","eyes":"...","skin":"...","body":"...","extra":"..."}}, the key is exactly the same as the entered character name; do not Markdown Code blocks, no explanations.`;

/** Field value cleanup: newlines squeezed into spaces, bbi_image-family sub-tag literals stripped (preventing corruption of the injection format). */
function sanitizeTagValue(value: unknown): string {
  const text = typeof value === 'string' ? value.trim().replace(/[\r\n]+/g, ' ') : '';
  if (!text) return '';
  if (/<\/?(?:bbi_image|tag|nl|size)\b/i.test(text)) return '';
  return text;
}

/** Parses {character name: {field: tag}} from the model reply (lenient: still parses with code fences/surrounding noise). */
export function parseConvertedTags(raw: string): Record<string, Partial<Record<CharTagField, string>>> {
  const cleaned = raw.replace(/<think(?:ing)?\b[\s\S]*?<\/think(?:ing)?>/gi, '');
  const candidates: string[] = [cleaned.trim()];
  for (const match of cleaned.matchAll(/```(?:json)?\s*([\s\S]*?)```/gi)) {
    candidates.unshift(match[1].trim());
  }
  for (const candidate of candidates) {
    const start = candidate.indexOf('{');
    const end = candidate.lastIndexOf('}');
    if (start < 0 || end <= start) continue;
    try {
      const value: unknown = JSON.parse(candidate.slice(start, end + 1));
      if (value && typeof value === 'object' && !Array.isArray(value)) {
        const out: Record<string, Partial<Record<CharTagField, string>>> = {};
        for (const [key, v] of Object.entries(value as Record<string, unknown>)) {
          const name = key.trim();
          if (!name || !v || typeof v !== 'object' || Array.isArray(v)) continue;
          const fields: Partial<Record<CharTagField, string>> = {};
          for (const f of CHAR_TAG_FIELDS) {
            const tag = sanitizeTagValue((v as Record<string, unknown>)[f]);
            if (tag) fields[f] = tag;
          }
          if (Object.keys(fields).length) out[name] = fields;
        }
        return out;
      }
    } catch {
      // Try the next candidate
    }
  }
  return {};
}

export interface ConvertedChar {
  name: string;
  desc: string;
  fields: Partial<Record<CharTagField, string>>;
}

/**
 * Converts CJK appearance text into structured fields in batch. One request converts every pending character.
 * Channel rule matches the main auto-tag flow: an assigned channel first, otherwise follow the main API.
 * Returns successfully converted entries; a total failure (request error) is thrown upward, and the caller catches and degrades.
 *
 * Only serves the character management page's "Generate from BaiBai Book's latest appearance" button, a one-off action the user clicks.
 * The main auto-tag flow no longer calls it: profile creation is done by the main request in the same output (see the file header).
 */
export async function generateCharTags(
  chars: Array<{ name: string; desc: string }>,
  signal?: AbortSignal,
): Promise<ConvertedChar[]> {
  if (!chars.length) return [];
  const messages: ChatMsg[] = [
    { role: 'system', content: CONVERT_SPEC },
    {
      role: 'user',
      content: chars.map(c => `- ${c.name}: ${c.desc}`).join('\n'),
    },
  ];
  const channel = getTagGenChannel();
  const raw = channel
    ? await requestCompletion(channel, messages, { signal, source: 'Character appearance transformation' })
    : await requestViaMainApi(messages, { signal, source: 'Character appearance transformation' });
  const parsed = parseConvertedTags(raw);
  const out: ConvertedChar[] = [];
  for (const c of chars) {
    const fields = parsed[c.name];
    if (fields) out.push({ name: c.name, desc: c.desc, fields });
  }
  return out;
}

/* ============ Main flow entry ============ */

/**
 * Library preparation before generation: renders the current library into the library text for the request.
 *
 * Pure function, no request: profile creation is handled by the main request (see the file header). This layer stays because callers still need
 * the "library text + library entries" pair, and @placeholder replacement must use the same entries as its baseline.
 * An empty library returns text=null, and the caller then doesn't enable @placeholders.
 */
export interface ResolvedCharAnchors {
  text: string | null;
  entries: CharTagEntry[];
}

export function resolveCharAnchors(
  entriesBefore: CharTagEntry[],
  lockedNames?: ReadonlySet<string>,
): ResolvedCharAnchors {
  const text = buildLibraryText(entriesBefore, lockedNames);
  return { text: text || null, entries: entriesBefore };
}

/* ============ @placeholder replacement ============ */

/** @name placeholder; names may contain CJK/letters/digits/dots/underscores/middle dots (common character-name forms). */
const REF_PATTERN = /@([\p{L}\p{N}_.·]+)/gu;

function joinEntryTag(entry: CharTagEntry): string {
  // Same shape as state/charTags.buildEntryTag; this small part is duplicated to avoid a circular dependency
  if (entry.raw.trim() && CHAR_TAG_FIELDS.every(f => !(entry.fields[f] ?? '').trim())) {
    return entry.raw.trim();
  }
  return CHAR_TAG_FIELDS.map(f => (entry.fields[f] ?? '').trim())
    .filter(Boolean)
    .join(', ');
}

/** Compresses separator garbage left after replacement: consecutive commas, commas at line start/end. */
function tidySeparators(text: string): string {
  let out = text;
  for (let i = 0; i < 4; i += 1) {
    const next = out.replace(/,\s*,/g, ',').replace(/\s+,/g, ',').replace(/,\s+/g, ', ');
    if (next === out) break;
    out = next;
  }
  return out.replace(/^[\s,]+/, '').replace(/[\s,]+$/, '').trim();
}

/**
 * Handles @placeholders in AI output text: names in the library → replaced with the latest tag string (in nl mode, preferring the entry's natural-language sentence);
 * names not in it → stripped (along with trailing separators). Returns the processed text and a list of unknown names (callers can use it for warnings).
 */
export function applyCharRefs(
  text: string,
  entries: CharTagEntry[],
  mode: 'tag' | 'nl' = 'tag',
): { text: string; unknown: string[] } {
  const byName = new Map(entries.map(e => [e.name, e]));
  const unknown: string[] = [];
  const seen = new Set<string>();
  const replaced = text.replace(REF_PATTERN, (_full, name: string) => {
    const entry = byName.get(name);
    if (entry) {
      if (mode === 'nl' && entry.nl.trim()) return entry.nl.trim();
      return joinEntryTag(entry);
    }
    if (!seen.has(name)) {
      seen.add(name);
      unknown.push(name);
    }
    return '';
  });
  return { text: tidySeparators(replaced), unknown };
}

export interface PositionedCharOp {
  op: CharTagAutoOp;
  sourceLine: number;
}

/**
 * Resolves @placeholders by image position.
 *
 * Profile creation (new) applies to the whole floor: a new character's fixed appearance is **a fact holding for the whole floor**, not a change "starting somewhere";
 * images earlier on the same floor may also have this character present. Gating by position would leave those images'
 * @placeholders without an entry, stripping them entirely, and the character would have no appearance.
 * Only permanent changes (set) are gated by position: images before a hair dye must use the old profile.
 */
export function applyPositionedCharRefs(
  text: string,
  entries: CharTagEntry[],
  ops: PositionedCharOp[],
  sourceLine: number,
  mode: 'tag' | 'nl' = 'tag',
  locked?: ReadonlySet<string>,
): { text: string; unknown: string[] } {
  const activeOps = ops
    .filter(item => item.op.kind === 'new' || item.sourceLine <= sourceLine)
    .map(item => item.op);
  return applyCharRefs(text, applyCharTagOps(entries, activeOps, -1, locked), mode);
}
